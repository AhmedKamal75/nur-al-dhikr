/** Map letter-skeleton coordinates to exact original UTF-16 word offsets.
 * Returns no annotation unless both pair letters and source words validate.
 * The 11:42 classification conflict stays Unknown under either convention. */
export function resolveConventionSites(text, surah, ayah, convention = 'dar-al-maarifah') {
  if (convention !== 'lpmq' || `${surah}:${ayah}` === '11:42') return [];
  const words = String(text || '')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  const letters = [];
  words.forEach((word, index) => {
    let offset = 0;
    for (const ch of word) {
      if (ch !== '\u0640' && /\p{L}/u.test(ch) && /\p{Script=Arabic}/u.test(ch)) {
        letters.push({ base: ch, wordIndex: index + 1, start: offset, end: offset + ch.length });
      }
      offset += ch.length;
    }
  });
  return TAJWEED_SITES.sites
    .filter((site) => site.ref === `${surah}:${ayah}`)
    .flatMap((site) => {
      const first = letters[site.quran.sakin_skeleton_offset];
      const follower = letters[site.quran.sakin_skeleton_offset + 1];
      if (
        !first ||
        !follower ||
        first.base !== site.sakin_letter ||
        follower.base !== site.follower_letter
      )
        return [];
      // Source words must also match a declared encoding's raw token positions.
      const matches = ['quran', 'mushaf'].some((corpus) => {
        const locator = site[corpus];
        return (
          first.wordIndex === (locator.word_whitespace || locator.word_a_whitespace) &&
          follower.wordIndex === (locator.word_whitespace || locator.word_b_whitespace)
        );
      });
      if (!matches) return [];
      return [
        {
          rule: site.rule,
          wordIndex: first.wordIndex,
          start: first.start,
          end: first.end,
          evidenceLevel: 'rule-level-cited',
          perSiteVisual: 'Unknown',
          ref: site.ref,
        },
      ];
    });
}
